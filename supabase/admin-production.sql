-- Bullseye Theory production database hardening and current-schema compatibility.
-- This is an idempotent SQL Editor script, not a migration-history entry.
-- It assumes the course catalogue tables (lessons, quizzes, quiz_questions, reels_queue)
-- already exist. Back up the project and review this script before applying it.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'student',
  is_admin boolean not null default false
);

create table if not exists public.course_access (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  is_active boolean not null default false,
  payment_verified boolean not null default false,
  expires_at timestamptz
);

create table if not exists public.lesson_progress (
  user_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  lesson_number integer not null,
  completed boolean not null default false,
  quiz_passed boolean not null default false,
  progress_percent integer not null default 0,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  lesson_number integer not null,
  score integer not null,
  passed boolean not null default false,
  attempted_at timestamptz not null default now()
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  student_name text not null default '',
  certificate_id text not null unique,
  issued_at timestamptz not null default now()
);


#!/usr/bin/env bash
set -euo pipefail

: "${DATABASE_URL:?DATABASE_URL must point to a disposable PostgreSQL database}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 <<'SQL'
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;

create schema auth;
create function auth.uid()
returns uuid
language sql
stable
as $ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $;
revoke all on function auth.uid() from public;
grant execute on function auth.uid() to authenticated, service_role;

create table public.profiles (
  id uuid primary key,
  full_name text not null default ''
);
create table public.course_access (
  user_id uuid primary key,
  is_active boolean not null default false,
  payment_verified boolean not null default false,
  expires_at timestamptz
);
create table public.certificates (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique,
  student_name text not null default '',
  certificate_id text not null unique,
  issued_at timestamptz not null default now()
);

create table public.lesson_progress (
  user_id uuid not null,
  lesson_number integer not null,
  completed boolean not null default false,
  quiz_passed boolean not null default false,
  progress_percent integer not null default 0,
  primary key (user_id, lesson_number)
);
create table public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  lesson_number integer not null,
  score integer not null default 0,
  passed boolean not null default false
);

alter table public.lesson_progress enable row level security;
alter table public.quiz_attempts enable row level security;

grant usage on schema public, auth to anon, authenticated, service_role;
grant select, insert, update, delete on public.lesson_progress, public.quiz_attempts to authenticated;
grant select on public.lesson_progress, public.quiz_attempts to service_role;
grant select on public.profiles, public.course_access, public.certificates to authenticated, service_role;

create policy "Students can view their own progress"
  on public.lesson_progress for select to authenticated using (true);
create policy "Students can insert their own progress"
  on public.lesson_progress for insert to authenticated with check (true);
create policy "Students can update their own progress"
  on public.lesson_progress for update to authenticated using (true) with check (true);
create policy "Legacy authenticated write policy"
  on public.lesson_progress for all to authenticated using (true) with check (true);

create policy "Students can view their own quiz attempts"
  on public.quiz_attempts for select to authenticated using (true);
create policy "Students can view their own certificate"
  on public.certificates for select to authenticated using (true);
create policy "Students can insert their own quiz attempts"
  on public.quiz_attempts for insert to authenticated with check (true);
SQL

psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 -f supabase/migrations/20261104190000_lock_course_progress_writes_to_edge_functions.sql

psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 <<'SQL'
do $assertions$
begin
  if has_table_privilege('authenticated', 'public.lesson_progress', 'INSERT')
     or has_table_privilege('authenticated', 'public.lesson_progress', 'UPDATE')
     or has_table_privilege('authenticated', 'public.lesson_progress', 'DELETE') then
    raise exception 'Authenticated role retained write privileges on lesson_progress';
  end if;
  if has_table_privilege('authenticated', 'public.quiz_attempts', 'INSERT')
     or has_table_privilege('authenticated', 'public.quiz_attempts', 'UPDATE')
     or has_table_privilege('authenticated', 'public.quiz_attempts', 'DELETE') then
    raise exception 'Authenticated role retained write privileges on quiz_attempts';
  end if;
  if not has_table_privilege('authenticated', 'public.lesson_progress', 'SELECT')
     or not has_table_privilege('authenticated', 'public.quiz_attempts', 'SELECT') then
    raise exception 'Authenticated read access for own progress/attempt policies was lost';
  end if;
  if not has_table_privilege('service_role', 'public.lesson_progress', 'SELECT')
     or not has_table_privilege('service_role', 'public.lesson_progress', 'INSERT')
     or not has_table_privilege('service_role', 'public.lesson_progress', 'UPDATE') then
    raise exception 'service_role is missing required lesson_progress privileges';
  end if;
  if not has_table_privilege('service_role', 'public.quiz_attempts', 'SELECT')
     or not has_table_privilege('service_role', 'public.quiz_attempts', 'INSERT') then
    raise exception 'service_role is missing required quiz_attempts privileges';
  end if;
  if not has_sequence_privilege('service_role', 'public.quiz_attempts_id_seq', 'USAGE') then
    raise exception 'service_role is missing quiz_attempts identity sequence usage';
  end if;
  if has_sequence_privilege('authenticated', 'public.quiz_attempts_id_seq', 'USAGE') then
    raise exception 'Authenticated role retained quiz_attempts sequence usage';
  end if;
  if exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename in ('lesson_progress', 'quiz_attempts')
      and cmd in ('INSERT', 'UPDATE', 'DELETE', 'ALL')
      and roles && array['public'::name, 'anon'::name, 'authenticated'::name]
  ) then
    raise exception 'A browser-role write policy remains on course progress or quiz attempts';
  end if;
  if not (select rolbypassrls from pg_roles where rolname = 'service_role') then
    raise exception 'service_role must bypass RLS for trusted Edge Function writes';
  end if;
end;
$assertions$;
SQL

# Prove trusted Edge Function operations still work after the lock-down.
psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 <<'SQL'
set role service_role;
insert into public.quiz_attempts (user_id, lesson_number, score, passed)
values ('00000000-0000-4000-8000-000000000003', 1, 80, true);
insert into public.lesson_progress (user_id, lesson_number, completed, quiz_passed, progress_percent)
values ('00000000-0000-4000-8000-000000000003', 1, false, true, 90);
update public.lesson_progress
set completed = true, progress_percent = 100
where user_id = '00000000-0000-4000-8000-000000000003' and lesson_number = 1;
reset role;
do $$
begin
  if not exists (select 1 from public.quiz_attempts where passed = true) then
    raise exception 'service_role could not insert a quiz attempt';
  end if;
  if not exists (select 1 from public.lesson_progress where completed = true and quiz_passed = true) then
    raise exception 'service_role could not update course completion';
  end if;
end;
$$;
SQL

echo "PASS: browser roles are read-only on authoritative progress and quiz attempts; service_role writes still work."


# Seed a verified learner who has completed all 11 lessons, and one incomplete learner.
psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 <<'SQL'
insert into public.profiles (id, full_name) values
  ('00000000-0000-4000-8000-000000000001', 'Completed Student'),
  ('00000000-0000-4000-8000-000000000002', 'Incomplete Student');
insert into public.course_access (user_id, is_active, payment_verified, expires_at) values
  ('00000000-0000-4000-8000-000000000001', true, true, now() + interval '1 day'),
  ('00000000-0000-4000-8000-000000000002', true, true, now() + interval '1 day');
insert into public.lesson_progress (user_id, lesson_number, completed, quiz_passed, progress_percent)
select '00000000-0000-4000-8000-000000000001', n, true, true, 100
from generate_series(1, 11) n;
insert into public.lesson_progress (user_id, lesson_number, completed, quiz_passed, progress_percent)
select '00000000-0000-4000-8000-000000000002', n, true, true, 100
from generate_series(1, 10) n;
SQL

CERT_ONE="$(psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 -qAtc "set role authenticated; set request.jwt.claim.sub = '00000000-0000-4000-8000-000000000001'; select public.issue_my_certificate(); reset role;")"
CERT_TWO="$(psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 -qAtc "set role authenticated; set request.jwt.claim.sub = '00000000-0000-4000-8000-000000000001'; select public.issue_my_certificate(); reset role;")"
if [[ "$CERT_ONE" != "$CERT_TWO" || ! "$CERT_ONE" =~ ^BT-[A-F0-9]{12}$ ]]; then
  echo "FAIL: certificate claim did not return a stable Bullseye certificate ID."
  exit 1
fi
psql "$DATABASE_URL" -X -v ON_ERROR_STOP=1 <<'SQL'
do $assert_incomplete$
begin
  perform set_config('request.jwt.claim.sub', '00000000-0000-4000-8000-000000000002', false);
  begin
    perform public.issue_my_certificate();
    raise exception 'Incomplete student unexpectedly received a certificate';
  exception when sqlstate '22023' then
    null;
  end;
end;
$assert_incomplete$;
SQL
CERT_COUNT="$(psql "$DATABASE_URL" -X -qAtc "select count(*) from public.certificates")"
if [[ "$CERT_COUNT" != "1" ]]; then
  echo "FAIL: incomplete student received a certificate or repeat claim duplicated it."
  exit 1
fi

echo "PASS: student certificate is issued only after 11 verified lesson completions and has a stable ID."
